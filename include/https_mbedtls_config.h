#undef MBEDTLS_SSL_ALPN
#undef MBEDTLS_SSL_MAX_FRAGMENT_LENGTH

/* The updater authenticates certificates, without pre-shared keys, static
 * RSA/ECDH key exchange or finite-field DH. RSA signatures remain enabled. */
