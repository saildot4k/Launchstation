#undef MBEDTLS_CIPHER_PADDING_ZEROS

/* Trust anchors are read through genOpen(). No key/certificate generation,
 * encrypted private-key files, persistent PSA keys or library self-tests. */
#undef MBEDTLS_FS_IO
