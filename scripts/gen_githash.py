"""Generate the installed-build identity shared by PS2BUILD and Makefile builds.

Run before compiling either controller variant. Source archives may use the
explicit local-build fallback; release CI requires a real Git checkout.
"""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile


def generate(repo, output, require_git=False):
    repo = Path(repo).resolve()
    output = Path(output)
    try:
        def git(*args):
            return subprocess.check_output(
                ["git", "-C", str(repo), *args], text=True,
                stderr=subprocess.DEVNULL,
            ).strip()

        # Do not accidentally stamp an enclosing, unrelated repository's SHA
        # onto a source archive unpacked inside that repository.
        if Path(git("rev-parse", "--show-toplevel")).resolve() != repo:
            raise ValueError("source directory is not the Git repository root")
        revision = git("rev-parse", "--verify", "HEAD")
        if not re.fullmatch(r"[0-9a-f]{40}", revision):
            raise ValueError("HEAD is not a full GitHub commit ID")
        date = json.dumps(git("show", "-s", "--format=%cI", "HEAD"))
    except (OSError, subprocess.CalledProcessError, ValueError) as exc:
        if require_git:
            raise ValueError("A Git checkout with a valid HEAD is required") from exc
        revision, date = "local", "__DATE__"

    content = (
        "/* Generated by scripts/gen_githash.py; do not edit. */\n"
        "#ifndef GIT_HASH\n"
        f"#define GIT_HASH {json.dumps(revision)}\n"
        "#endif\n"
        "#ifndef ULE_VERDATE\n"
        f"#define ULE_VERDATE {date}\n"
        "#endif\n"
    ).encode("utf-8")
    # Preserve timestamps on an unchanged checkout so Make/Ninja can reuse
    # objects, but replace the header atomically whenever HEAD changes.
    if not output.exists() or output.read_bytes() != content:
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=output.parent, delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(content)
            os.replace(temporary, output)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
    return revision


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=root / "githash.h")
    parser.add_argument("--require-git", action="store_true")
    args = parser.parse_args()
    try:
        revision = generate(root, args.output, args.require_git)
    except (OSError, ValueError) as exc:
        parser.exit(1, f"Build identity generation failed: {exc}\n")
    print(f"Build identity: {revision}")
